export const FONT_CHARS = Object.keys(G).join('');
export const CELL_W = 6;
export const CELL_H = 9;

/** Рисует атлас шрифта и регистрирует его как bitmap font `key`. */
export function registerPixelFont(scene, key = 'px') {
  const chars = FONT_CHARS;
  const w = chars.length * CELL_W;
  const tex = scene.textures.createCanvas(key, w, CELL_H);
  const ctx = tex.getContext();
  [...chars].forEach((ch, i) => {
    const rows = G[ch];
    const ox = i * CELL_W;
    // тень
    ctx.fillStyle = 'rgba(10,6,16,0.85)';
    rows.forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') ctx.fillRect(ox + x, y + 1, 1, 1); });
    ctx.fillStyle = '#ffffff';
    rows.forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') ctx.fillRect(ox + x, y, 1, 1); });
  });
  tex.refresh();

  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: key,
    width: CELL_W,
    height: CELL_H,
    chars,
    charsPerRow: chars.length,
    spacing: { x: 0, y: 0 },
    offset: { x: 0, y: 0 },
    lineSpacing: 2
  });
  scene.cache.bitmapFont.add(key, data);
}

/** Приводит строку к набору символов шрифта (регистр, ё, неизвестные символы). */
export function normalizeText(str) {
  let out = '';
  for (const ch of String(str).toUpperCase()) {
    if (G[ch] || ch === '\n') out += ch;
    else if (ch === 'Ё') out += 'Ё';
    else if (ch === '–') out += '-';
    else if (ch === '№') out += '#';
    else out += ' ';
  }
  return out;
}
